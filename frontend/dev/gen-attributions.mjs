/**
 * Generates the credit list from `dev/attributions.mjs` into its two destinations:
 *
 *   - `src/generated/attributions.ts` — read by the About page.
 *   - `THIRD-PARTY-NOTICES.md`        — the index section, between the generated markers.
 *
 * One source, two outputs, because they are the same claim made to two audiences: a visitor reading
 * `/about` and someone auditing the repository. Maintained separately they drift, and a credit list that
 * has quietly stopped matching what ships is worse than none — it looks maintained.
 *
 * The hand-written part of `THIRD-PARTY-NOTICES.md` above the marker is never touched: full licence texts
 * for work redistributed inside the artefacts are a legal record that wants human review, not generation.
 *
 * Run: `npm run attributions`. CI regenerates and diffs.
 */

import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

import attributions from './attributions.mjs';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const REPO = join(ROOT, '..');

const BEGIN = '<!-- BEGIN GENERATED CREDITS -->';
const END = '<!-- END GENERATED CREDITS -->';

const duplicates = attributions
  .map((a) => a.name)
  .filter((name, i, all) => all.indexOf(name) !== i);
if (duplicates.length > 0) throw new Error(`attributions.mjs: duplicate entr(ies) ${duplicates.join(', ')}`);

for (const a of attributions) {
  for (const field of ['name', 'license', 'url', 'scope', 'note']) {
    if (!a[field]) throw new Error(`attributions.mjs: "${a.name ?? '?'}" is missing ${field}`);
  }
  if (a.scope !== 'runtime' && a.scope !== 'build') {
    throw new Error(`attributions.mjs: "${a.name}" has scope "${a.scope}", expected runtime or build`);
  }
}

// ---- src/generated/attributions.ts ----

const ts = `// SPDX-License-Identifier: AGPL-3.0-or-later
// SPDX-FileCopyrightText: 2026 The Mosaicast Authors
//
// @generated by dev/gen-attributions.mjs — DO NOT EDIT.
// Run \`npm run attributions\` after changing dev/attributions.mjs.

/** One project Mosaicast is built on, as credited on the About page. */
export interface Attribution {
  name: string;
  /** Pinned version, where naming one is meaningful; absent when the version is governed elsewhere. */
  version?: string;
  /** SPDX identifier. Displayed verbatim and never translated — it is an identifier, not prose. */
  license: string;
  url: string;
  /** \`runtime\` ships inside the artefacts; \`build\` is used to make them and never shipped. */
  scope: 'runtime' | 'build';
  /** What it does *for Mosaicast*, in one line. */
  note: string;
}

/** Everything Mosaicast is built on, in the order the About page lists it. */
export const ATTRIBUTIONS: readonly Attribution[] = ${JSON.stringify(attributions, null, 2)
  .replace(/^/gm, '')
  .replace(/"([a-z]+)":/g, '$1:')} as const;
`;

mkdirSync(join(ROOT, 'src', 'generated'), { recursive: true });
writeFileSync(join(ROOT, 'src', 'generated', 'attributions.ts'), ts);

// ---- THIRD-PARTY-NOTICES.md ----

const noticesPath = join(REPO, 'THIRD-PARTY-NOTICES.md');
const notices = readFileSync(noticesPath, 'utf8');
const begin = notices.indexOf(BEGIN);
const end = notices.indexOf(END);
if (begin === -1 || end === -1) {
  throw new Error(`THIRD-PARTY-NOTICES.md is missing the ${BEGIN} / ${END} markers`);
}

/** One markdown table for a scope, or nothing when that scope is empty. */
function table(scope, heading, blurb) {
  const rows = attributions.filter((a) => a.scope === scope);
  if (rows.length === 0) return '';
  return [
    `### ${heading}`,
    '',
    blurb,
    '',
    '| Project | Licence | What it does here |',
    '| --- | --- | --- |',
    ...rows.map((a) => {
      const name = a.version ? `[${a.name}](${a.url}) ${a.version}` : `[${a.name}](${a.url})`;
      return `| ${name} | \`${a.license}\` | ${a.note} |`;
    }),
    '',
  ].join('\n');
}

const generated = [
  BEGIN,
  '',
  '<!-- Generated by frontend/dev/gen-attributions.mjs from frontend/dev/attributions.mjs.',
  '     Edit that file and run `npm run attributions`; edits here are overwritten. -->',
  '',
  table('runtime', 'Ships in the artefacts', 'Present in the shell bundle, the server JAR or the container image.'),
  table('build', 'Used to build and test', 'Never shipped — but the work is no less real, so it is credited too.'),
  END,
].join('\n');

writeFileSync(noticesPath, notices.slice(0, begin) + generated + notices.slice(end + END.length));

const runtime = attributions.filter((a) => a.scope === 'runtime').length;
console.log(`attributions.ts        ${attributions.length} projects (${runtime} runtime, ${attributions.length - runtime} build)`);
console.log(`THIRD-PARTY-NOTICES.md generated section rewritten`);
